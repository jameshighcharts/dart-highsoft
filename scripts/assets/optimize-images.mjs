#!/usr/bin/env node
// Builds the images the app serves from the full-size originals in scripts/assets/originals:
// WebP at three times the size they are shown at (sharp on 3x phone screens), written to
// src/assets/images, plus the module that imports them (src/assets/images/index.ts).
//
// The app imports them, so Next serves each under a content-hashed URL cached for a year
// (`immutable`): a changed image gets a new URL, an unchanged one is never fetched again.
//
// Usage: node scripts/assets/optimize-images.mjs (after changing anything in originals/)
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ORIGINALS = path.join(ROOT, 'scripts/assets/originals');
const OUTPUT = path.join(ROOT, 'src/assets/images');
const SCALE = 3;
const QUALITY = 92;

// `width` is the largest CSS width the image is shown at.
const GROUPS = [
  { dir: 'elo-badges', exportName: 'ELO_BADGES', width: 132, key: (name) => Number(name.replace('tier-', '')) },
  { dir: 'elo-badges-full', exportName: 'ELO_BADGES_FULL', width: 132, key: (name) => Number(name.replace('tier-', '')) },
  { dir: 'location-badges', exportName: 'LOCATION_BADGES', width: 76, key: (name) => name },
  { dir: 'default-avatars', exportName: 'DEFAULT_AVATARS', width: 80, key: (name) => name },
];

const identifier = (dir, name) =>
  `${dir}-${name}`.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, '');

await rm(OUTPUT, { recursive: true, force: true });
const imports = [];
const exports = [];
for (const group of GROUPS) {
  await mkdir(path.join(OUTPUT, group.dir), { recursive: true });
  const names = (await readdir(path.join(ORIGINALS, group.dir)))
    .filter((file) => file.endsWith('.png'))
    .map((file) => file.slice(0, -'.png'.length))
    .sort();
  const entries = [];
  for (const name of names) {
    const out = path.join(OUTPUT, group.dir, `${name}.webp`);
    // Never upscale: an original smaller than 3x stays at its own size.
    const info = await sharp(path.join(ORIGINALS, group.dir, `${name}.png`))
      .resize({ width: group.width * SCALE, withoutEnlargement: true })
      .webp({ quality: QUALITY, alphaQuality: 100, effort: 6 })
      .toFile(out);
    console.log(`${group.dir}/${name}.webp ${info.width}x${info.height} ${Math.round(info.size / 1024)} KB`);
    const id = identifier(group.dir, name);
    imports.push(`import ${id} from './${group.dir}/${name}.webp';`);
    entries.push(`  ${JSON.stringify(group.key(name))}: ${id},`);
  }
  exports.push(`export const ${group.exportName} = {\n${entries.join('\n')}\n} as const;`);
}

await writeFile(path.join(OUTPUT, 'index.ts'), `// Generated by scripts/assets/optimize-images.mjs from scripts/assets/originals; do not edit.
${imports.join('\n')}

${exports.join('\n\n')}
`);
